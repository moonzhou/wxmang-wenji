def order_index(series, title):
    """按人工顺序表返回 0-based 序号；未登记返回 None（调用方回落日期序）。"""
    seq = SERIES_ORDER.get(series)
    if not seq:
        return None
    try:
        return seq.index(title)
    except ValueError:
        return None


def series_sort_key(series, rec):
    """系列内排序键：人工顺序表优先，未登记的标题排在该系列末尾（再按日期）。

    为什么要给「未登记」一个明确的大数而不是 None：
        sorted 会对同位置键做比较，None 与 int 不可比会直接抛 TypeError。
        给未登记项一个「排在已知项之后」的序号，既不炸，也能让新增未登记
        篇目落在末尾提醒人补登记——而不是静默插到中间某个位置。
    """
    idx = order_index(series, rec.get("title", ""))
    if idx is None:
        idx = 10 ** 6
    return (idx, rec.get("date", ""), rec.get("id", 0))


